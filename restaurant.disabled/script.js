const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

document.addEventListener('DOMContentLoaded', () => {
    const navbar = document.getElementById('navbar');

    /* -------------------------------------------------- Navbar scroll state */
    const onNavScroll = () => {
        navbar.classList.toggle('scrolled', window.scrollY > 50);
    };
    onNavScroll();
    window.addEventListener('scroll', onNavScroll, { passive: true });

    /* -------------------------------------------------- Language switching */
    const langSelectors = document.querySelectorAll('.lang-btn');

    function setLanguage(lang) {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang][key]) {
                if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                    el.placeholder = translations[lang][key];
                } else if (el.tagName === 'OPTION') {
                    el.textContent = translations[lang][key];
                } else {
                    el.innerHTML = translations[lang][key];
                }
            }
        });

        document.title = translations[lang]['page_title'];
        langSelectors.forEach(btn => {
            btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
        });
        document.documentElement.lang = lang;
        localStorage.setItem('preferredLang', lang);
    }

    langSelectors.forEach(btn => {
        btn.addEventListener('click', () => setLanguage(btn.getAttribute('data-lang')));
    });

    const savedLang = localStorage.getItem('preferredLang') || 'de';
    setLanguage(savedLang);

    /* -------------------------------------------------- Mobile menu toggle */
    const mobileNavToggle = document.getElementById('mobileNavToggle');
    const navLinks = document.getElementById('navLinks');

    const closeMobileNav = () => {
        if (navLinks && navLinks.classList.contains('active')) {
            mobileNavToggle.classList.remove('active');
            navLinks.classList.remove('active');
            mobileNavToggle.setAttribute('aria-expanded', 'false');
            mobileNavToggle.setAttribute('aria-label', 'Menü öffnen');
        }
    };

    if (mobileNavToggle) {
        mobileNavToggle.addEventListener('click', () => {
            const isExpanded = mobileNavToggle.classList.toggle('active');
            navLinks.classList.toggle('active');
            mobileNavToggle.setAttribute('aria-expanded', String(isExpanded));
            mobileNavToggle.setAttribute('aria-label', isExpanded ? 'Menü schließen' : 'Menü öffnen');
        });
    }

    /* -------------------------------------------------- Reservation modal */
    const reservationModal = document.getElementById('reservationModal');
    const reservationTriggers = document.querySelectorAll('#navReservation, #heroReservation, #bandReservation');
    const closeModalBtn = document.getElementById('closeModal');
    const modalOverlay = document.getElementById('modalOverlay');
    let lastFocusedElement = null;

    if (reservationModal && reservationTriggers.length > 0) {
        const getFocusableElements = () => reservationModal.querySelectorAll(
            'button, [href], input, select, textarea, [tabindex]:not([tabindex="-1"])'
        );

        const openModal = (e) => {
            e.preventDefault();
            lastFocusedElement = document.activeElement;
            reservationModal.classList.add('active');
            reservationModal.setAttribute('aria-hidden', 'false');
            document.body.style.overflow = 'hidden';
            setTimeout(() => closeModalBtn.focus(), 100);
            closeMobileNav();
        };

        const closeModal = () => {
            reservationModal.classList.remove('active');
            reservationModal.setAttribute('aria-hidden', 'true');
            document.body.style.overflow = '';
            if (lastFocusedElement) lastFocusedElement.focus();
        };

        reservationTriggers.forEach(t => t.addEventListener('click', openModal));
        closeModalBtn.addEventListener('click', closeModal);
        modalOverlay.addEventListener('click', closeModal);

        document.addEventListener('keydown', (e) => {
            if (!reservationModal.classList.contains('active')) return;
            if (e.key === 'Escape') { closeModal(); return; }
            if (e.key === 'Tab') {
                const focusable = getFocusableElements();
                const first = focusable[0];
                const last = focusable[focusable.length - 1];
                if (e.shiftKey && document.activeElement === first) {
                    e.preventDefault(); last.focus();
                } else if (!e.shiftKey && document.activeElement === last) {
                    e.preventDefault(); first.focus();
                }
            }
        });
    }

    /* -------------------------------------------------- Smooth anchor scroll */
    document.querySelectorAll('a[href^="#"]:not([href="#reservation"])').forEach(anchor => {
        anchor.addEventListener('click', function (e) {
            const targetId = this.getAttribute('href');
            if (targetId === '#') return;
            const target = document.querySelector(targetId);
            if (!target) return;
            e.preventDefault();
            closeMobileNav();
            const offset = target.getBoundingClientRect().top + window.pageYOffset - 70;
            window.scrollTo({ top: offset, behavior: prefersReducedMotion ? 'auto' : 'smooth' });
        });
    });

    /* -------------------------------------------------- Scroll reveal */
    const revealEls = document.querySelectorAll('[data-reveal]');
    if (prefersReducedMotion || !('IntersectionObserver' in window)) {
        revealEls.forEach(el => el.classList.add('is-visible'));
    } else {
        const revealObserver = new IntersectionObserver((entries, obs) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('is-visible');
                    obs.unobserve(entry.target);
                }
            });
        }, { threshold: 0.15, rootMargin: '0px 0px -8% 0px' });
        revealEls.forEach(el => revealObserver.observe(el));
    }

    /* -------------------------------------------------- Image parallax */
    const parallaxEls = Array.from(document.querySelectorAll('[data-parallax]'));
    if (!prefersReducedMotion && parallaxEls.length) {
        let ticking = false;
        const applyParallax = () => {
            const vh = window.innerHeight;
            parallaxEls.forEach(el => {
                const rect = el.getBoundingClientRect();
                if (rect.bottom < 0 || rect.top > vh) return;
                const speed = parseFloat(el.dataset.parallax) || 0.1;
                const progress = (rect.top + rect.height / 2 - vh / 2) / vh;
                el.style.transform = `translate3d(0, ${(progress * speed * 100).toFixed(2)}px, 0)`;
            });
            ticking = false;
        };
        const requestParallax = () => {
            if (!ticking) { ticking = true; requestAnimationFrame(applyParallax); }
        };
        window.addEventListener('scroll', requestParallax, { passive: true });
        window.addEventListener('resize', requestParallax, { passive: true });
        applyParallax();
    }

    /* -------------------------------------------------- Scrollspy nav */
    const spySections = ['home', 'about', 'experience', 'location']
        .map(id => document.getElementById(id))
        .filter(Boolean);
    const navAnchors = document.querySelectorAll('.nav-links > a[href^="#"]');
    if (spySections.length && 'IntersectionObserver' in window) {
        const spyObserver = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    const id = entry.target.id;
                    navAnchors.forEach(a => a.classList.toggle('active', a.getAttribute('href') === `#${id}`));
                }
            });
        }, { rootMargin: '-45% 0px -50% 0px' });
        spySections.forEach(s => spyObserver.observe(s));
    }

    /* -------------------------------------------------- Count-up rating stats */
    const counters = document.querySelectorAll('.rating-number[data-count]');
    if (counters.length) {
        const runCount = (el) => {
            const target = parseFloat(el.dataset.count);
            const decimals = parseInt(el.dataset.decimals || '0', 10);
            if (prefersReducedMotion) { el.textContent = target.toFixed(decimals); return; }
            const duration = 1200;
            let start = null;
            const step = (ts) => {
                if (start === null) start = ts;
                const p = Math.min((ts - start) / duration, 1);
                const eased = 1 - Math.pow(1 - p, 3);
                el.textContent = (target * eased).toFixed(decimals);
                if (p < 1) requestAnimationFrame(step);
                else el.textContent = target.toFixed(decimals);
            };
            requestAnimationFrame(step);
        };
        if ('IntersectionObserver' in window) {
            const countObserver = new IntersectionObserver((entries, obs) => {
                entries.forEach(entry => {
                    if (entry.isIntersecting) { runCount(entry.target); obs.unobserve(entry.target); }
                });
            }, { threshold: 0.6 });
            counters.forEach(c => countObserver.observe(c));
        } else {
            counters.forEach(runCount);
        }
    }

    /* -------------------------------------------------- Testimonials carousel */
    const track = document.getElementById('testimonialsTrack');
    const prevBtn = document.getElementById('testiPrev');
    const nextBtn = document.getElementById('testiNext');
    const dotsWrap = document.getElementById('testiDots');

    if (track && prevBtn && nextBtn) {
        const cards = Array.from(track.children);
        let page = 0;
        let pageCount = 1;
        let perView = 1;
        let autoplayId = null;
        const AUTOPLAY_DELAY = 5500;

        const metrics = () => {
            const cardW = cards[0].getBoundingClientRect().width;
            const gap = parseFloat(getComputedStyle(track).gap) || 0;
            const viewportW = track.parentElement.clientWidth;
            perView = Math.max(1, Math.round(viewportW / (cardW + gap)));
            pageCount = Math.max(1, Math.ceil(cards.length / perView));
            return { cardW, gap, viewportW };
        };

        const buildDots = () => {
            if (!dotsWrap) return;
            dotsWrap.innerHTML = '';
            for (let i = 0; i < pageCount; i++) {
                const dot = document.createElement('button');
                dot.className = 'slider-dot' + (i === page ? ' active' : '');
                dot.setAttribute('role', 'tab');
                dot.setAttribute('aria-label', `Seite ${i + 1}`);
                dot.addEventListener('click', () => { goTo(i); resetAutoplay(); });
                dotsWrap.appendChild(dot);
            }
        };

        const goTo = (i) => {
            const { cardW, gap, viewportW } = metrics();
            page = (i + pageCount) % pageCount;
            let offset = page * perView * (cardW + gap);
            const maxOffset = Math.max(0, track.scrollWidth - viewportW);
            offset = Math.min(offset, maxOffset);
            track.style.transform = `translate3d(-${offset}px, 0, 0)`;
            if (dotsWrap) {
                Array.from(dotsWrap.children).forEach((d, idx) =>
                    d.classList.toggle('active', idx === page));
            }
        };

        const rebuild = () => { metrics(); buildDots(); goTo(Math.min(page, pageCount - 1)); };

        const startAutoplay = () => {
            if (prefersReducedMotion || autoplayId || pageCount <= 1) return;
            autoplayId = setInterval(() => goTo(page + 1), AUTOPLAY_DELAY);
        };
        const stopAutoplay = () => { clearInterval(autoplayId); autoplayId = null; };
        const resetAutoplay = () => { stopAutoplay(); startAutoplay(); };

        nextBtn.addEventListener('click', () => { goTo(page + 1); resetAutoplay(); });
        prevBtn.addEventListener('click', () => { goTo(page - 1); resetAutoplay(); });

        const container = track.closest('.testimonials');
        container.addEventListener('mouseenter', stopAutoplay);
        container.addEventListener('mouseleave', startAutoplay);
        container.addEventListener('focusin', stopAutoplay);
        container.addEventListener('focusout', startAutoplay);

        let resizeTimer;
        window.addEventListener('resize', () => {
            clearTimeout(resizeTimer);
            resizeTimer = setTimeout(rebuild, 150);
        });

        rebuild();
        startAutoplay();
    }

    /* -------------------------------------------------- Back to top */
    const backToTopBtn = document.getElementById('backToTop');
    if (backToTopBtn) {
        window.addEventListener('scroll', () => {
            backToTopBtn.classList.toggle('visible', window.scrollY > 500);
        }, { passive: true });
        backToTopBtn.addEventListener('click', () => {
            window.scrollTo({ top: 0, behavior: prefersReducedMotion ? 'auto' : 'smooth' });
        });
    }
});
